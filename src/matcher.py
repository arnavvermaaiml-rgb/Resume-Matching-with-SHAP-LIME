"""
Ranking engine behind the Streamlit app.

Takes a job built from free-form requirements plus a pool of applicants
(bundled synthetic resumes and/or parsed uploads), computes the 7 slide-5
features for every applicant against that job, scores them with the trained
Logistic Regression, and explains each score with SHAP.
"""
import json
from pathlib import Path

import joblib
import numpy as np
import pandas as pd
import shap
from sklearn.metrics.pairwise import cosine_similarity

from feature_engineering import compute_features
from report_candidate import FEATURE_LABELS, NEGATIVE_PHRASES, POSITIVE_PHRASES, narrative
from resume_parser import parse_resume
from skills import normalize_skill, normalize_skills
from train_model import FEATURES

ROOT = Path(__file__).resolve().parent.parent
EDU_LABEL = {"associate": "Associate's", "bachelor": "Bachelor's", "master": "Master's", "phd": "PhD"}


# ---------------------------------------------------------------------------
# Artifacts
# ---------------------------------------------------------------------------
class Artifacts:
    """Everything trained/generated by the pipeline, loaded once."""

    def __init__(self):
        missing = [p for p in ("outputs/model.pkl", "outputs/tfidf.pkl", "data/dataset.csv", "data/resumes.json", "data/jobs.json")
                   if not (ROOT / p).exists()]
        if missing:
            raise FileNotFoundError(
                f"Missing {missing}. Run: python src/author_dataset.py, feature_engineering.py, train_model.py first."
            )
        self.model = joblib.load(ROOT / "outputs" / "model.pkl")
        self.vectorizer = joblib.load(ROOT / "outputs" / "tfidf.pkl")
        background = pd.read_csv(ROOT / "data" / "dataset.csv")[FEATURES]
        self.explainer = shap.LinearExplainer(
            self.model, shap.maskers.Independent(background, max_samples=len(background))
        )
        with open(ROOT / "data" / "jobs.json", encoding="utf-8") as f:
            self.jobs = json.load(f)
        with open(ROOT / "data" / "resumes.json", encoding="utf-8") as f:
            self.pool = json.load(f)
        metrics_path = ROOT / "outputs" / "metrics.json"
        self.metrics = json.load(open(metrics_path)) if metrics_path.exists() else {}


# ---------------------------------------------------------------------------
# Job construction
# ---------------------------------------------------------------------------
def split_terms(text: str) -> list:
    """'Python, SQL; machine learning\\nPandas' -> ['python', 'sql', 'machine learning', 'pandas']"""
    parts = [p.strip().lower() for chunk in text.replace(";", ",").splitlines() for p in chunk.split(",")]
    seen, out = set(), []
    for p in parts:
        if p and normalize_skill(p) not in seen:
            seen.add(normalize_skill(p))
            out.append(p)
    return out


def build_description(job: dict) -> str:
    """Job-description text written in the same register as the training descriptions."""
    req = ", ".join(job["required_skills"])
    pref = ", ".join(job["preferred_skills"])
    tech = ", ".join(job["technologies"])
    text = (
        f"We are seeking a {job['title']} to join our team. The ideal candidate will have strong experience in {req}. "
    )
    if pref:
        text += f"Experience with {pref} is a plus. "
    text += (
        f"Requires a minimum of {job['min_experience']} years of relevant experience and a "
        f"{job['education']}. "
    )
    if tech:
        text += f"Our stack is built on {tech}."
    return text


def make_job(title, required, preferred, technologies, min_experience, education_level,
             fields=None, description="") -> dict:
    required, preferred, technologies = list(required), list(preferred), list(technologies)
    job = {
        "id": "CUSTOM",
        "title": title.strip() or "Open role",
        "required_skills": required,
        "preferred_skills": preferred,
        # The model's technology feature needs a non-empty tool list; default to the required skills.
        "technologies": technologies or required,
        "min_experience": float(min_experience),
        "education_level": education_level,
        "education": EDU_LABEL[education_level] + (f" in {', '.join(fields)}" if fields else " degree"),
        "related_fields": list(fields) if fields else None,
        "adjacent_fields": [] if fields else None,
    }
    job["description_text"] = description.strip() or build_description(job)
    return job


# ---------------------------------------------------------------------------
# Scoring
# ---------------------------------------------------------------------------
def _skill_gaps(candidate_skills, job_skills):
    cand = normalize_skills(candidate_skills)
    matched = [s for s in job_skills if normalize_skill(s) in cand]
    missing = [s for s in job_skills if normalize_skill(s) not in cand]
    return matched, missing


def prepare_candidates(job: dict, pool: list, uploads: list) -> list:
    """
    pool    : structured resume dicts (bundled dataset)
    uploads : [{"filename": str, "text": str}] raw text from uploaded files
    Uploads are parsed per job so any skill typed into the requirements is detected, not just a fixed list.
    """
    extra = job["required_skills"] + job["preferred_skills"] + job["technologies"]
    candidates = []
    for r in pool:
        candidates.append({**r, "source": "Pool", "key": r["id"], "email": "", "warnings": []})
    for up in uploads:
        parsed = parse_resume(up["text"], up["filename"], extra_terms=extra)
        parsed.update({"source": "Uploaded", "key": f"U:{up['filename']}", "id": f"U:{up['filename']}"})
        candidates.append(parsed)
    return candidates


def score_candidates(art: Artifacts, job: dict, candidates: list) -> pd.DataFrame:
    """One row per candidate with features, probability, SHAP contributions and skill gaps."""
    if not candidates:
        return pd.DataFrame()

    job_vec = art.vectorizer.transform([job["description_text"]])
    resume_vecs = art.vectorizer.transform([c["resume_text"] for c in candidates])
    sims = cosine_similarity(resume_vecs, job_vec).ravel()

    feats = pd.DataFrame(
        [compute_features(c, job, float(sim)) for c, sim in zip(candidates, sims)]
    )[FEATURES]
    proba = art.model.predict_proba(feats)[:, 1]
    shap_values = art.explainer(feats).values

    rows = []
    for i, c in enumerate(candidates):
        req_matched, req_missing = _skill_gaps(c["skills"], job["required_skills"])
        pref_matched, pref_missing = _skill_gaps(c["skills"], job["preferred_skills"])
        contribs = dict(zip(FEATURES, shap_values[i].tolist()))
        pos = [f for f, v in sorted(contribs.items(), key=lambda kv: -kv[1]) if v > 0]
        neg = [f for f, v in sorted(contribs.items(), key=lambda kv: kv[1]) if v < 0]
        rows.append({
            "key": c["key"],
            "name": c["name"],
            "source": c["source"],
            "email": c.get("email", ""),
            "score": float(proba[i]),
            "verdict": "Good match" if proba[i] >= 0.5 else "Poor match",
            "experience_years": c["experience_years"],
            "education": c["education"],
            "required_matched": req_matched,
            "required_missing": req_missing,
            "preferred_matched": pref_matched,
            "preferred_missing": pref_missing,
            "contributions": contribs,
            "narrative": narrative(c["name"], job["title"], float(proba[i]), pos, neg),
            "warnings": c.get("warnings", []),
            "projects": c.get("projects", []),
            "skills": c["skills"],
            **{f: float(feats.iloc[i][f]) for f in FEATURES},
        })
    df = pd.DataFrame(rows).sort_values("score", ascending=False).reset_index(drop=True)
    df.insert(0, "rank", df.index + 1)
    return df


